#!/bin/bash
# Agentic SDLC Framework: Kanban & Traceability Synchronizer
# Queries GitHub Issues and generates a living docs/KANBAN.md board with a full Traceability Matrix

set -e

OUTPUT_FILE="docs/KANBAN.md"
mkdir -p docs

echo "⚡ Fetching GitHub issues and milestones for living board..."

# Verify gh CLI is authenticated
if ! command -v gh &> /dev/null; then
    echo "⚠️ gh CLI not found. Please install gh to use kanban-sync."
    exit 1
fi

REPO=$(gh repo view --json nameWithOwner -q .nameWithOwner 2>/dev/null || echo "Current Repository")
TIMESTAMP=$(date -u +"%Y-%m-%d %H:%M:%S UTC")

# Fetch issues in JSON format including body for spec link parsing
ISSUES_JSON=$(gh issue list --state all --limit 100 --json number,title,url,state,labels,milestone,body 2>/dev/null || echo "[]")

cat << 'EOF' > "$OUTPUT_FILE"
# 📋 Project Kanban Board & Traceability Matrix

> **Living Project State & Audit Trail**  
> Auto-generated by `sdlc-kanban` via GitHub API.  
> To refresh this board: `.agent/skills/sdlc-kanban/scripts/kanban-sync.sh`

EOF

echo "> **Repository**: \`$REPO\`  " >> "$OUTPUT_FILE"
echo "> **Last Synced**: \`$TIMESTAMP\`" >> "$OUTPUT_FILE"
echo "" >> "$OUTPUT_FILE"

cat << 'EOF' >> "$OUTPUT_FILE"
---

## 📊 Board Overview

| 📥 Backlog | 📋 Ready | ⚡ In Progress | 🔍 In Review | ✅ Done |
| :--- | :--- | :--- | :--- | :--- |
EOF

# Parse issues into columns and traceability matrix using python
python3 - "$ISSUES_JSON" << 'PYEOF' >> "$OUTPUT_FILE"
import json
import sys
import re

raw = sys.argv[1] if len(sys.argv) > 1 else "[]"
try:
    issues = json.loads(raw)
except Exception:
    issues = []

cols = {
    'backlog': [],
    'ready': [],
    'in_progress': [],
    'in_review': [],
    'done': []
}

traceability_rows = []

for issue in issues:
    num = issue.get('number')
    title = issue.get('title', '').replace('|', '\\|')
    url = issue.get('url', f"#{num}")
    state = issue.get('state', 'OPEN')
    labels = [l.get('name') for l in issue.get('labels', [])]
    milestone = issue.get('milestone')
    ms_tag = f" `[{milestone.get('title')}]`" if milestone else ""
    body = issue.get('body', '') or ''

    # Determine status
    if state == 'CLOSED' or 'status:done' in labels:
        status_label = 'status:done'
        cols['done'].append(f"[#{num} {title}]({url}){ms_tag}")
    elif 'status:in-review' in labels:
        status_label = 'status:in-review'
        cols['in_review'].append(f"[#{num} {title}]({url}){ms_tag}")
    elif 'status:in-progress' in labels:
        status_label = 'status:in-progress'
        cols['in_progress'].append(f"[#{num} {title}]({url}){ms_tag}")
    elif 'status:ready' in labels:
        status_label = 'status:ready'
        cols['ready'].append(f"[#{num} {title}]({url}){ms_tag}")
    else:
        status_label = 'status:backlog'
        cols['backlog'].append(f"[#{num} {title}]({url}){ms_tag}")

    # Extract Priority
    priority = "P2 - Medium"
    priority_map = {
        "priority:critical": "P0 - Critical",
        "priority:high": "P1 - High",
        "priority:medium": "P2 - Medium",
        "priority:low": "P3 - Low"
    }
    for l in labels:
        if l in priority_map:
            priority = priority_map[l]
        elif l.startswith("priority:"):
            priority = l.replace("priority:", "").capitalize()

    # Extract Component
    component = "Architecture"
    for l in labels:
        if l.startswith("component:"):
            raw_comp = l.replace("component:", "")
            component = "DevOps" if raw_comp == "devops" else raw_comp.capitalize()

    # Extract Quality Gate
    gate = "Pending"
    for l in labels:
        if l.startswith("gate:"):
            gate = l.replace("gate:", "").capitalize()

    # Look for spec / PRD links in body
    spec_match = re.search(r'\[(SPEC-\d+|PRD|SRS|Spec|Architecture)[^\]]*\]\(([^)]+)\)', body, re.IGNORECASE)
    if spec_match:
        spec_link = f"[{spec_match.group(1)}]({spec_match.group(2)})"
    elif "PRODUCT.md" in body:
        spec_link = "[PRODUCT.md](PRODUCT.md)"
    else:
        spec_link = "—"

    traceability_rows.append({
        'num': num,
        'title': title,
        'url': url,
        'status': f"`{status_label}`",
        'milestone': milestone.get('title') if milestone else "—",
        'priority': priority,
        'component': component,
        'gate': f"`{gate}`",
        'spec': spec_link
    })

max_rows = max(len(v) for v in cols.values()) if any(cols.values()) else 0

for i in range(max_rows):
    b = cols['backlog'][i] if i < len(cols['backlog']) else ""
    r = cols['ready'][i] if i < len(cols['ready']) else ""
    p = cols['in_progress'][i] if i < len(cols['in_progress']) else ""
    rv = cols['in_review'][i] if i < len(cols['in_review']) else ""
    d = cols['done'][i] if i < len(cols['done']) else ""
    print(f"| {b} | {r} | {p} | {rv} | {d} |")

print("\n---\n")
print("## 🎯 End-to-End Traceability Matrix\n")
print("| Issue | Status | Priority | Component | Quality Gate | Spec Link |")
print("| :--- | :--- | :--- | :--- | :--- | :--- |")

for row in sorted(traceability_rows, key=lambda x: x['num'], reverse=True):
    print(f"| [#{row['num']} {row['title']}]({row['url']}) | {row['status']} | {row['priority']} | {row['component']} | {row['gate']} | {row['spec']} |")

PYEOF

echo "" >> "$OUTPUT_FILE"
cat << 'EOF' >> "$OUTPUT_FILE"
---

### 🏷️ Kanban Label Convention
* `status:backlog` - Triaged, in queue for specification.
* `status:ready` - Specification approved (`sdlc-feature-spec`), ready for engineering.
* `status:in-progress` - Active branch and TDD implementation underway.
* `status:in-review` - Pull Request open, peer review (`sdlc-peer-review`) & quality gate active.
* `status:done` - Merged, verified, and closed.
EOF

echo "✅ Generated $OUTPUT_FILE successfully with Traceability Matrix."
